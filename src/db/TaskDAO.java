package db;

import models.Task;

import java.sql.*;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

public class TaskDAO {

    // Fetch all tasks for the logged-in user
    public List<Task> getTasksForUser(int userId) {
        List<Task> tasks = new ArrayList<>();
        String query = "SELECT * FROM tasks WHERE user_id = ? ORDER BY id DESC";

        try (Connection conn = DatabaseManager.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(query)) {

            pstmt.setInt(1, userId);
            try (ResultSet rs = pstmt.executeQuery()) {
                while (rs.next()) {
                    Date sqlDate = rs.getDate("target_date");
                    LocalDate targetDate = (sqlDate != null) ? sqlDate.toLocalDate() : LocalDate.now();

                    tasks.add(new Task(
                            rs.getInt("id"),
                            rs.getInt("user_id"),
                            rs.getString("title"),
                            rs.getString("description"),
                            targetDate,
                            rs.getBoolean("is_completed"),
                            rs.getBoolean("is_auto_generated")
                    ));
                }
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
        return tasks;
    }

    // Insert a new task into the database
    public void createTask(Task task) {
        String query = "INSERT INTO tasks (user_id, title, description, target_date, is_completed, is_auto_generated) VALUES (?, ?, ?, ?, ?, ?)";

        try (Connection conn = DatabaseManager.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(query)) {

            pstmt.setInt(1, task.getUserId());
            pstmt.setString(2, task.getTitle());
            pstmt.setString(3, task.getDescription() != null ? task.getDescription() : "");
            pstmt.setDate(4, Date.valueOf(task.getTargetDate()));
            pstmt.setBoolean(5, task.isCompleted());
            pstmt.setBoolean(6, task.isAutoGenerated());

            pstmt.executeUpdate();

        } catch (SQLException e) {
            e.printStackTrace();
        }
    }

    // Update completion status when the user clicks the checkbox
    public void updateTaskCompletion(int taskId, boolean isCompleted) {
        String query = "UPDATE tasks SET is_completed = ? WHERE id = ?";

        try (Connection conn = DatabaseManager.getConnection();
             PreparedStatement pstmt = conn.prepareStatement(query)) {

            pstmt.setBoolean(1, isCompleted);
            pstmt.setInt(2, taskId);
            pstmt.executeUpdate();

        } catch (SQLException e) {
            e.printStackTrace();
        }
    }
}