package models;

import java.time.LocalDate;

public class Task {
    private int id;
    private int userId;
    private String title;
    private String description;
    private LocalDate dueDate;
    private boolean completed;
    private boolean autoGenerated;

    public Task() {}

    public Task(int id, String title, boolean completed) {
        this.id = id;
        this.title = title;
        this.completed = completed;
    }

    public Task(String title, String dueDate, boolean completed) {
        this.title = title;
        this.dueDate = dueDate != null && !dueDate.equals("Today") ? LocalDate.parse(dueDate) : LocalDate.now();
        this.completed = completed;
    }

    public Task(int id, int userId, String title, String description, LocalDate dueDate, boolean completed, boolean autoGenerated) {
        this.id = id;
        this.userId = userId;
        this.title = title;
        this.description = description;
        this.dueDate = dueDate;
        this.completed = completed;
        this.autoGenerated = autoGenerated;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public int getUserId() {
        return userId;
    }

    public void setUserId(int userId) {
        this.userId = userId;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public LocalDate getDueDate() {
        return dueDate;
    }

    public String getDueDateString() {
        return dueDate != null ? dueDate.toString() : "Today";
    }

    public void setDueDate(LocalDate dueDate) {
        this.dueDate = dueDate;
    }

    public boolean isCompleted() {
        return completed;
    }

    public void setCompleted(boolean completed) {
        this.completed = completed;
    }

    public boolean isAutoGenerated() {
        return autoGenerated;
    }

    public void setAutoGenerated(boolean autoGenerated) {
        this.autoGenerated = autoGenerated;
    }
}